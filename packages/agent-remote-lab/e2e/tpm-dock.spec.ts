test('TPM groups remain usable while multiple workspaces are open', async ({ page, isMobile }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/e2e/fixtures/tpm-dock.html');
  const trigger = page.getByRole('button', { name: 'TPM works', exact: true });
  await trigger.click();
  const list = page.getByRole('region', { name: 'TPM works', exact: true });
  await expect(list.getByRole('heading', { name: 'Agent Remote Control', includeHidden: true })).toHaveCount(2);
  await expect(list.getByRole('heading', { name: 'Website reliability' })).toBeVisible();
  await list.locator('[data-tpm-work]').filter({ hasText: 'Search delivery' }).click();
  await expect(page.getByRole('dialog', { name: 'TPM: Search delivery' })).toBeVisible();
  await expect(trigger).toBeVisible(); await expect(list).toBeVisible();
  await list.locator('[data-tpm-work]').filter({ hasText: 'Connection recovery' }).click();
  const second = page.getByRole('dialog', { name: 'TPM: Connection recovery' });
  await expect(second).toBeVisible();
  await expect(second.getByRole('button', { name: 'Open main session: Agent Remote Control', exact: true })).toBeVisible();
  await expect(page.locator('.lab-tpm-window:visible')).toHaveCount(isMobile ? 1 : 2);
  await list.getByRole('button', { name: 'Close TPM works' }).click();
  await second.getByTestId('prompt-input').fill('Preserve this delivery draft');
  await second.getByRole('button', { name: 'Back to TPM works' }).click();
  await expect(second).toBeVisible(); await expect(list).toBeVisible();
  await second.locator('.lab-tpm-heading').click({ position: { x: 8, y: 8 } });
  await expect(list).toBeVisible();
  await list.locator('[data-tpm-work]').filter({ hasText: 'Search delivery' }).click();
  await list.locator('[data-tpm-work]').filter({ hasText: 'Connection recovery' }).click();
  await expect(second.getByTestId('prompt-input')).toContainText('Preserve this delivery draft');
  await list.getByRole('button', { name: 'Close TPM works' }).click();
  await second.getByRole('button', { name: 'Stop and archive TPM session' }).click();
  await expect(list).toBeVisible(); await expect(second).toBeVisible();
  const archived = list.locator('.lab-tpm-archived');
  await archived.locator('summary').click();
  await expect(archived.getByRole('heading', { name: 'Agent Remote Control' })).toBeVisible();
  await expect(archived.locator('[data-tpm-work]').filter({ hasText: 'Connection recovery' })).toBeVisible();
  await expect(list.locator(':scope > .lab-tpm-group [data-tpm-work]').filter({ hasText: 'Connection recovery' })).toHaveCount(0);
  if (isMobile) await expect(page.getByRole('button', { name: /^Dock / })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('tpm-groups.png') });
  expect(errors).toEqual([]);
});

test('desktop Dock preserves sessions, resizes and reorders only the appended views', async ({ page, isMobile }, testInfo) => {
  test.skip(isMobile, 'Dock is a desktop presentation.');
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/e2e/fixtures/tpm-dock.html');
  const trigger = page.getByRole('button', { name: 'TPM works', exact: true });
  const list = page.getByRole('region', { name: 'TPM works', exact: true });
  for (const title of ['Search delivery', 'Connection recovery']) {
    await trigger.click();
    await list.locator('[data-tpm-work]').filter({ hasText: title }).click();
    await list.getByRole('button', { name: 'Close TPM works' }).click();
    const view = page.getByRole('dialog', { name: `TPM: ${title}` });
    await view.getByTestId('prompt-input').fill(`Draft for ${title}`);
    await view.getByTestId('prompt-input').evaluate(element => { element.setAttribute('data-instance', 'original'); });
    await clickSessionAction(view, `Dock ${title}`);
    await expect(page.locator('.lab-session-dock-pane').filter({ hasText: title })).toBeVisible();
    await expect(view.getByTestId('prompt-input')).toHaveAttribute('data-instance', 'original');
  }
  await expect(page.locator('.lab-session-dock-pane')).toHaveCount(2);
  const connections = await page.locator('html').getAttribute('data-fixture-connections');
  const first = page.getByRole('region', { name: 'Docked Search delivery', exact: true });
  const second = page.getByRole('region', { name: 'Docked Connection recovery', exact: true });
  const separator = first.getByRole('separator');
  await separator.focus(); await separator.press('ArrowRight');
  await expect(separator).toHaveAttribute('aria-valuenow', '450');
  const boundary = (await separator.boundingBox())!;
  await page.mouse.move(boundary.x + 3, boundary.y + 200); await page.mouse.down();
  await page.mouse.move(boundary.x + 53, boundary.y + 200, { steps: 8 }); await page.mouse.up();
  await expect(separator).toHaveAttribute('aria-valuenow', '500');
  const handle = second.locator('[data-session-title-draggable]').first();
  await handle.scrollIntoViewIfNeeded();
  const grip = (await handle.boundingBox())!, target = (await first.boundingBox())!;
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2); await page.mouse.down();
  await page.mouse.move(target.x + target.width / 3, grip.y + grip.height / 2, { steps: 20 });
  await page.mouse.up();
  await expect.poll(async () => Number(await second.evaluate(element => (element as HTMLElement).style.order))).toBe(1);
  await expect(first).toHaveCSS('order', '2');
  await expect(page.locator('.lab-session-dock-base .lab-primary-conversation')).toHaveCount(1);
  await expect(page.locator('.lab-session-dock-base .lab-side-conversation')).toHaveCount(1);
  await expect(page.locator('.lab-session-dock-base [aria-label^="Move "]')).toHaveCount(0);
  await page.locator('.lab-session-dock-rail').evaluate(element => { element.scrollLeft = 0; });
  const main = page.locator('.lab-primary-conversation');
  const child = page.locator('.lab-side-conversation');
  await main.getByTestId('prompt-input').fill('Keep the main draft');
  await main.getByTestId('prompt-input').evaluate(element => element.setAttribute('data-instance', 'original-main'));
  const originalWidth = (await page.locator('.lab-session-dock-base').boundingBox())!.width;
  const minimize = page.getByRole('button', { name: 'Minimize main session area' });
  await minimize.focus(); await minimize.press('Enter');
  await expect(main).toBeHidden(); await expect(child).toBeHidden();
  const restore = page.getByRole('button', { name: 'Restore main session: Agent Remote Control' });
  await expect(restore).toBeFocused();
  expect((await page.locator('.lab-session-dock-base').boundingBox())!.width).toBe(44);
  await expect(first).toBeVisible(); await expect(second).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('main-minimized.png') });
  await restore.click();
  await expect(main).toBeVisible(); await expect(child).toBeVisible();
  await expect(main.getByTestId('prompt-input')).toHaveAttribute('data-instance', 'original-main');
  await expect(main.getByTestId('prompt-input')).toHaveText('Keep the main draft');
  expect((await page.locator('.lab-session-dock-base').boundingBox())!.width).toBe(originalWidth);
  await expect(page.getByRole('button', { name: 'Minimize main session area' })).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath('dock-reordered.png') });
  await clickSessionAction(first, 'Float Search delivery');
  const floating = page.getByRole('dialog', { name: 'TPM: Search delivery' });
  await expect(floating.getByTestId('prompt-input')).toHaveAttribute('data-instance', 'original');
  await expect(floating.getByTestId('prompt-input')).toContainText('Draft for Search delivery');
  await expect(page.locator('html')).toHaveAttribute('data-fixture-connections', connections!);
  await floating.getByRole('button', { name: 'Minimize TPM', exact: true }).click();
  await page.locator('.lab-session-dock-rail').evaluate(element => { element.scrollLeft = 0; });
  await page.getByRole('button', { name: 'Open Ask', exact: true }).click();
  const ask = page.getByRole('dialog', { name: 'Ask', exact: true });
  await ask.getByRole('textbox', { name: 'Ask draft' }).fill('Ask stays the same view');
  await clickSessionAction(ask, 'Dock Ask');
  await expect(page.getByRole('region', { name: 'Docked Ask', exact: true })).toBeVisible();
  await clickSessionAction(ask, 'Float Ask');
  await expect(ask.getByRole('textbox', { name: 'Ask draft' })).toHaveValue('Ask stays the same view');
  expect(errors).toEqual([]);
});

test('Dock follows viewport width even on touch devices and restores after narrowing', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 1024 });
  await page.goto('/e2e/fixtures/tpm-dock.html');
  await page.getByRole('button', { name: 'TPM works', exact: true }).click();
  const list = page.getByRole('region', { name: 'TPM works', exact: true });
  await list.locator('[data-tpm-work]').filter({ hasText: 'Search delivery' }).click();
  await list.getByRole('button', { name: 'Close TPM works' }).click();
  const view = page.getByRole('dialog', { name: 'TPM: Search delivery' });
  const composer = view.getByTestId('prompt-input');
  await composer.fill('Keep this draft across layout changes');
  await composer.evaluate(element => element.setAttribute('data-instance', 'before-resize'));
  await clickSessionAction(view, 'Dock Search delivery');
  await expect(page.locator('.lab-session-dock-pane')).toHaveCount(1);
  const connections = await page.locator('html').getAttribute('data-fixture-connections');
  await page.getByRole('button', { name: 'Minimize main session area' }).click();
  await page.setViewportSize({ width: 820, height: 1180 });
  await expect(page.locator('.lab-primary-conversation')).toBeVisible();
  await expect(page.getByRole('button', { name: /^(Dock|Float) Search delivery$/ })).toHaveCount(0);
  await expect(page.locator('.lab-session-dock-pane')).toHaveCount(0);
  await expect(view).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(composer).toHaveAttribute('data-instance', 'before-resize');
  await page.setViewportSize({ width: 1366, height: 1024 });
  await expect(page.getByRole('region', { name: 'Docked Search delivery', exact: true })).toBeVisible();
  await expect(composer).toHaveAttribute('data-instance', 'before-resize');
  await expect(composer).toContainText('Keep this draft across layout changes');
  await expect(page.locator('.lab-primary-conversation')).toBeHidden();
  await clickSessionAction(view, 'Float Search delivery');
  await expect(page.locator('.lab-primary-conversation')).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-fixture-connections', connections!);
});

test('TPM delegation is explicit and quiet reviews use the ordinary session view', async ({ page }, testInfo) => {
  await page.goto('/e2e/fixtures/tpm-dock.html');
  await page.getByRole('button', { name: 'TPM works', exact: true }).click();
  const list = page.getByRole('region', { name: 'TPM works', exact: true });
  await list.locator('[data-tpm-work]').filter({ hasText: 'Search delivery' }).click();
  await list.getByRole('button', { name: 'Close TPM works' }).click();
  const view = page.getByRole('dialog', { name: 'TPM: Search delivery' });
  const delegation = view.getByRole('button', { name: 'Background delegation' });
  await expect(delegation).toHaveAttribute('aria-pressed', 'false');
  await view.getByTestId('prompt-input').fill('Continue discussing the scope');
  await delegation.click(); await expect(delegation).toHaveAttribute('aria-pressed', 'true');
  await expect(view.getByTestId('prompt-input')).toContainText('Continue discussing the scope');
  await view.getByRole('button', { name: 'Minimize TPM', exact: true }).click();
  await page.getByRole('button', { name: 'TPM works', exact: true }).click();
  await list.locator('[data-tpm-work]').filter({ hasText: 'Search delivery' }).click();
  await list.getByRole('button', { name: 'Close TPM works' }).click();
  await expect(delegation).toHaveAttribute('aria-pressed', 'true');
  await delegation.click(); await expect(delegation).toHaveAttribute('aria-pressed', 'false');
  await view.getByTestId('timeline').focus();
  await view.getByTestId('timeline').press('Home');
  const checks = view.getByRole('button', { name: /Background checks/ });
  await expect(checks).toBeInViewport();
  await expect(checks).toHaveAttribute('aria-expanded', 'false');
  await expect(view.getByText('Review 1:', { exact: false })).toHaveCount(0);
  await checks.click(); await expect(checks).toHaveAttribute('aria-expanded', 'true');
  await expect(view.getByText('Review 1:', { exact: false })).toHaveCount(1);
  await checks.click();
  await page.screenshot({ path: testInfo.outputPath('tpm-delegation.png') });
});

test('reload restores multiple TPM docks with their widths, order and drafts', async ({ page, isMobile }) => {
  test.skip(isMobile, 'Dock uses a wide workspace.');
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto('/e2e/fixtures/tpm-dock.html');
  for (const title of ['Search delivery', 'Connection recovery']) {
    await page.getByRole('button', { name: 'TPM works', exact: true }).click();
    const list = page.getByRole('region', { name: 'TPM works', exact: true });
    await list.locator('[data-tpm-work]').filter({ hasText: title }).click();
    await list.getByRole('button', { name: 'Close TPM works' }).click();
    const view = page.getByRole('dialog', { name: `TPM: ${title}` });
    await view.getByTestId('prompt-input').fill(`Draft for ${title}`);
    await clickSessionAction(view, `Dock ${title}`);
  }
  const first = page.getByRole('region', { name: 'Docked Search delivery', exact: true });
  const second = page.getByRole('region', { name: 'Docked Connection recovery', exact: true });
  await second.locator('[data-session-title-draggable]').first().focus();
  await second.locator('[data-session-title-draggable]').first().press('Alt+ArrowLeft');
  await first.getByRole('separator').focus(); await first.getByRole('separator').press('ArrowRight');
  await page.reload();
  await expect(first).toBeVisible(); await expect(second).toBeVisible();
  await expect(first).toHaveCSS('order', '2'); await expect(second).toHaveCSS('order', '1');
  await expect(first.getByRole('separator')).toHaveAttribute('aria-valuenow', '450');
  await expect(first.getByTestId('prompt-input')).toHaveText('Draft for Search delivery');
  await expect(second.getByTestId('prompt-input')).toHaveText('Draft for Connection recovery');
});
