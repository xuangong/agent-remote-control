import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from '@playwright/test';
import { createDebuggerServer } from '../src/server.js';
import { createBrowserPrefixAdapter } from './fixtures/browser-prefix-adapter.mjs';

test('ARDB Live edits its native prefix and retains drafts until the matching admission ACK', async ({ page }, info) => {
  const directory = await mkdtemp(join(tmpdir(), 'ardb-prefix-browser-'));
  const adapter = createBrowserPrefixAdapter(directory);
  const server = await createDebuggerServer({ adapter, port: 0, config: { sessionId: 'A', cwd: directory },
    successionStateDirectory: join(directory, 'state'), assetsDirectory: fileURLToPath(new URL('../dist/web', import.meta.url)) });
  const failures: string[] = [], operations: string[] = [], admissions: string[] = [], observations: string[] = [];
  page.on('websocket', socket => socket.on('framereceived', event => { const payload = String(event.payload); if (/command_acknowledged|protocol_error/.test(payload)) admissions.push(payload); if (payload.includes('agent_stream')) observations.push(payload); }));
  page.on('pageerror', error => failures.push(error.message));
  page.on('request', request => { if (request.url().includes('/__ardb/succession/')) operations.push(new URL(request.url()).pathname); });
  let releaseDescription: (() => void) | undefined;
  try {
    let described = false;
    const descriptionGate = new Promise<void>(resolve => { releaseDescription = resolve; });
    await page.route('**/__ardb/succession/describe', async route => {
      const response = await route.fetch(); described = true;
      await descriptionGate; await route.fulfill({ response });
    });
    await page.goto(server.url);
    const editor = page.getByTestId('prompt-input');
    await expect(editor).toBeVisible();
    await expect.poll(() => described).toBe(true);
    await expect(editor).toBeDisabled();
    releaseDescription!();
    await expect(editor).toHaveAttribute('contenteditable', 'true');
    await page.unroute('**/__ardb/succession/describe');
    const row = page.locator('[data-prompt-editable]').filter({ hasText: 'selected prompt' });
    await expect(row.locator('[data-prompt-edit-action]:visible')).toHaveCount(1);
    await row.hover(); await row.locator('[data-prompt-edit-action]:visible').click();
    await expect(editor).toHaveText('selected prompt');
    await expect(page.locator('.lab-handoff-notice')).toHaveCount(0);
    await expect.poll(async () => (await adapter.state()).forks).toBe(1);
    expect((await adapter.state()).sessions['candidate-1'].inputs).toEqual([]);
    expect(operations.filter(path => path.endsWith('/prepare'))).toHaveLength(1);
    expect(operations.filter(path => path.endsWith('/commit'))).toHaveLength(1);
    await page.reload(); await expect(editor).toHaveText('selected prompt');
    await editor.fill('echo before ACK'); await editor.press('Enter');
    await expect.poll(() => adapter.pendingInput()).toBe('echo before ACK');
    await expect.poll(() => observations.join('\n')).toContain('echo before ACK');
    await expect(page.getByRole('region', { name: 'Agent timeline' }).getByText('echo before ACK', { exact: true })).toBeVisible();
    await expect(editor).toHaveText('echo before ACK');
    adapter.settleInput(true); await expect(editor).toHaveText('');
    await page.reload(); await expect(editor).toHaveText(''); await expect(editor).toHaveAttribute('contenteditable', 'true');
    await editor.fill('rejected draft'); await editor.press('Enter');
    await expect.poll(() => adapter.pendingInput()).toBe('rejected draft');
    await expect.poll(() => observations.join('\n')).toContain('rejected draft');
    await expect(page.getByRole('region', { name: 'Agent timeline' }).getByText('rejected draft', { exact: true })).toBeVisible();
    adapter.settleInput(false);
    await expect.poll(() => admissions.join('\n')).toContain('fixture_rejected');
    await expect(editor).toHaveText('rejected draft');
    await page.reload(); await expect(editor).toHaveText('rejected draft');
    expect(failures).toEqual([]);
    await page.screenshot({ path: info.outputPath('ardb-prefix-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(editor).toBeVisible();
    await page.screenshot({ path: info.outputPath('ardb-prefix-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.getByRole('button', { name: 'Show debug controls' }).click();
    await page.getByRole('button', { name: 'Record', exact: true }).click();
    await expect(page.getByLabel('Recording active')).toBeVisible();
    await page.getByRole('button', { name: 'Stop recording', exact: true }).click();
    const downloaded = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Export JSONL' }).click();
    await (await downloaded).saveAs(join(directory, 'prefix-recording.jsonl'));
    await page.getByRole('button', { name: 'Open recording', exact: true }).click();
    await page.getByRole('button', { name: 'prefix-recording.jsonl JSONL', exact: true }).click();
    await expect(editor).toBeDisabled();
    const position = page.getByRole('slider', { name: 'Playback position' });
    await position.fill(await position.getAttribute('max') ?? '0');
    await expect(page.locator('[data-prompt-edit-action]')).toHaveCount(0);
    expect(operations.filter(path => path.endsWith('/prepare'))).toHaveLength(1);
    expect(failures).toEqual([]);
  } finally { releaseDescription?.(); adapter.settleInput(false); await server.close(); await rm(directory, { recursive: true, force: true }); }
});
