import { expect, test, type Locator } from '@playwright/test';
import { showNewSession } from './session-navigation';

async function navigateConversation(primary: Locator, direction: 'Back' | 'Forward'): Promise<void> {
  const button = primary.getByRole('button', { name: direction === 'Back' ? 'Back to previous conversation' : 'Forward to next conversation', exact: true });
  const expand = primary.getByRole('button', { name: 'Expand session actions', exact: true });
  if (await expand.isVisible()) await expand.click();
  if (!await button.isVisible()) await primary.getByRole('button', { name: 'More session actions', exact: true }).click();
  await button.click();
}

test('main navigation, reload and browser history retain an independent docked Ask', async ({ page, isMobile }) => {
  test.skip(isMobile, 'Dock uses a wide workspace.');
  await page.setViewportSize({ width: 1600, height: 1000 });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const creations: unknown[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname.endsWith('/create')) creations.push(request.postDataJSON()); });
  await page.goto('/');
  await showNewSession(page); await page.getByTestId('session-create').click();
  const primary = page.locator('.lab-primary-conversation > .lab-session-view');
  const input = primary.getByTestId('prompt-input');
  await expect(input).toBeEnabled();
  const first = new URL(page.url()).searchParams.get('session');
  const askCreated = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/create'));
  await input.fill('/ask Remember the independent workspace'); await input.press('Enter');
  const askIdentity = await (await askCreated).json() as { nativeSessionId: string };
  const ask = page.getByRole('dialog', { name: 'Ask', exact: true });
  await expect(ask.locator('.agent-message-assistant').last()).toContainText('Remember the independent workspace');
  await ask.getByTestId('prompt-input').fill('Retain the dock draft');
  await ask.getByTestId('prompt-input').evaluate(element => element.setAttribute('data-instance', 'retained'));
  await ask.getByRole('button', { name: 'Dock Ask', exact: true }).click();
  const dock = page.getByRole('region', { name: 'Docked Ask', exact: true });
  await dock.getByRole('separator').focus(); await dock.getByRole('separator').press('ArrowRight');
  await page.locator('.lab-session-dock-rail').evaluate(element => { element.scrollLeft = 0; });
  await input.fill('/side Keep the paired child'); await input.press('Enter');
  await expect(page.locator('.lab-side-conversation .agent-message-assistant').last()).toContainText('Keep the paired child');
  await showNewSession(page);
  const secondCreated = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/create'));
  await page.getByTestId('session-create').click();
  const second = (await (await secondCreated).json() as { nativeSessionId: string }).nativeSessionId;
  await expect(page).toHaveURL(url => url.searchParams.get('session') === second);
  await expect(input).toBeEnabled();
  expect(second).not.toBe(first);
  await expect(dock).toBeVisible();
  await expect(ask.getByTestId('prompt-input')).toHaveAttribute('data-instance', 'retained');
  await primary.getByRole('button', { name: 'Minimize main session area' }).click();
  await expect(primary).toBeHidden();
  await expect(dock).toBeVisible();
  const count = creations.length;
  let offline = true;
  await page.route('**/v1/remote/attach', async route => {
    if (offline && route.request().postDataJSON().nativeSessionId === askIdentity.nativeSessionId) await route.fulfill({ status: 503, json: { error: 'Ask temporarily offline' } });
    else await route.continue();
  });
  await page.reload();
  await expect(ask.getByRole('alert')).toContainText('Ask temporarily offline');
  offline = false;
  await ask.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(dock).toBeVisible();
  await expect(dock.getByRole('separator')).toHaveAttribute('aria-valuenow', '450');
  await expect(ask.getByTestId('prompt-input')).toHaveText('Retain the dock draft');
  await expect(ask.locator('.agent-message-assistant').last()).toContainText('Remember the independent workspace');
  await expect(primary).toBeHidden();
  await page.getByRole('button', { name: /^Restore main session:/ }).click();
  await expect(primary).toBeVisible();
  await navigateConversation(primary, 'Back');
  await expect(page.locator('.lab-side-conversation:visible .agent-message-assistant').last()).toContainText('Keep the paired child');
  await expect(dock).toBeVisible();
  await navigateConversation(primary, 'Forward');
  await expect(page).toHaveURL(url => url.searchParams.get('session') === second);
  await expect(dock).toBeVisible();
  await ask.getByRole('button', { name: 'Float Ask', exact: true }).click();
  await expect(ask).toBeVisible();
  await expect(ask.getByTestId('prompt-input')).toHaveText('Retain the dock draft');
  expect(creations).toHaveLength(count);
  expect(errors).toEqual([]);
});

test('browser navigation restores the selected main and Side composition after refresh', async ({ page }) => {
  await page.goto('/'); await showNewSession(page);
  await page.getByTestId('session-create').click();
  const primary = page.locator('.lab-primary-conversation > .lab-session-view');
  await expect(primary.getByTestId('prompt-input')).toBeEnabled();
  await primary.getByTestId('prompt-input').fill('/side Restore this selected child');
  await primary.getByTestId('prompt-input').press('Enter');
  const side = page.locator('.lab-side-conversation:visible .agent-message-assistant').last();
  await expect(side).toContainText('Restore this selected child');
  await showNewSession(page);
  const selected = new URL(page.url()).searchParams.get('session');
  const created = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/create'));
  await page.getByTestId('session-create').click();
  const next = (await (await created).json() as { nativeSessionId: string }).nativeSessionId;
  await expect(page).toHaveURL(url => url.searchParams.get('session') === next);
  await navigateConversation(primary, 'Back');
  await expect(side).toContainText('Restore this selected child');
  await expect(page).toHaveURL(url => url.searchParams.get('session') === selected);
  await page.reload();
  await expect(side).toContainText('Restore this selected child');
  await expect(page).toHaveURL(url => url.searchParams.get('session') === selected);
  await page.goForward();
  await expect(page).toHaveURL(url => url.searchParams.get('session') === next);
  await expect(primary).toBeVisible();
});

test('global View stays usable while the main composition is minimized', async ({ page, isMobile }, testInfo) => {
  test.skip(isMobile, 'Minimization applies to wide dock layouts.');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/'); await showNewSession(page); await page.getByTestId('session-create').click();
  const primary = page.locator('.lab-primary-conversation > .lab-session-view');
  const input = primary.getByTestId('prompt-input');
  await expect(input).toBeEnabled();
  await input.fill('/ask Keep working in the dock'); await input.press('Enter');
  const ask = page.getByRole('dialog', { name: 'Ask', exact: true });
  await expect(ask.getByTestId('prompt-input')).toBeEnabled();
  await ask.getByRole('button', { name: 'Dock Ask', exact: true }).click();
  const view = page.getByRole('button', { name: 'View options', exact: true });
  const options = page.getByRole('region', { name: 'View options', exact: true });
  await view.click(); await options.getByRole('button', { name: 'Hide all', exact: true }).click();
  await options.press('Escape');
  await primary.getByRole('button', { name: 'Minimize main session area' }).click();
  await expect(primary).toBeHidden();
  await expect(view).toBeVisible();
  await expect(view).toHaveCount(1);
  await page.reload();
  await expect(primary).toBeHidden(); await expect(view).toBeVisible();
  await view.click(); await options.getByRole('checkbox', { name: 'Sidebar', exact: true }).check();
  await options.press('Escape');
  await page.getByRole('button', { name: 'Sidebar settings', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Controller settings', exact: true })).toBeVisible();
  await expect(primary).toBeHidden();
  await view.click(); await options.getByRole('checkbox', { name: 'Sidebar', exact: true }).uncheck();
  await options.getByRole('checkbox', { name: 'Header', exact: true }).check();
  await expect(page.locator('.lab-app-bar').getByRole('button', { name: 'View options', exact: true })).toBeVisible();
  await options.getByRole('checkbox', { name: 'Header', exact: true }).uncheck();
  await options.press('Escape');
  await expect(view).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('minimized-global-view.png') });
  await page.setViewportSize({ width: 820, height: 1180 });
  await expect(primary).toBeVisible();
  await expect(page.getByRole('button', { name: 'Minimize main session area' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: /^Restore main session:/ })).toHaveCount(0);
  await expect(page.locator('.lab-mobile-navigation').getByRole('button', { name: 'View options', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect(primary).toBeHidden(); await expect(view).toBeVisible();
  await page.getByRole('button', { name: /^Restore main session:/ }).click();
  await expect(primary.getByRole('button', { name: 'View options', exact: true })).toBeVisible();
  await expect(view).toHaveCount(1);
});
